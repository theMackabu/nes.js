import glob, os, sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
output = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "build", "demos.h")
sources = sys.argv[2:] if len(sys.argv) > 2 else glob.glob(os.path.join(root, "demos", "*.js"))
os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
out = ["/* generated by mkdemos.py */", "#define DEMO_BANK 5", '#pragma rodata-name(push, "DEMOS")']
meta, ok = [], True

for i, f in enumerate(sorted(sources)):
    text = open(f).read().rstrip("\n") + "\n"
    lines = text.rstrip("\n").split("\n")
    for n, l in enumerate(lines, 1):
        if len(l) > 47: print(f"{f}:{n}: line too long ({len(l)})"); ok = False
    if len(lines) > 64: print(f"{f}: too many lines"); ok = False
    if len(text) > 1700: print(f"{f}: too big"); ok = False
    body = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    out.append(f'static const char demo{i}[] = "{body}";')
    desc = lines[0][2:].strip() if lines[0].startswith("//") else ""
    meta.append((os.path.basename(f)[3:-3].upper(), desc, f"demo{i}", len(text)))

out.append("#pragma rodata-name(pop)")
out.append(f"#define NDEMOS {len(meta)}")
out.append("static const char *const demo_title[] = {" + ", ".join(f'"{t}"' for t, *_ in meta) + "};")
out.append("static const char *const demo_desc[] = {" + ", ".join(f'"{d}"' for _, d, *_ in meta) + "};")
out.append("static const char *const demo_src[] = {" + ", ".join(v for *_, v, _ in meta) + "};")
out.append("static const unsigned int demo_len[] = {" + ", ".join(str(n) for *_, n in meta) + "};")

open(output, "w").write("\n".join(out) + "\n")
print("demos:", [t for t, *_ in meta])
sys.exit(0 if ok else 1)
