from PIL import PcfFontFile
from fontlib import IBM
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
fontdir = root / 'assets' / 'fonts'
outdir = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'build'
outdir.mkdir(parents=True, exist_ok=True)

def rev(b): return int(f"{b:08b}"[::-1], 2)
tiles = [[[0]*8, [0]*8] for _ in range(128)]

for c in range(32, 127):
    tiles[c - 32] = [[rev(b) for b in IBM[c]], [0]*8]
tiles[95] = [[0xFF]*8, [0]*8]
tiles[96] = [[0xF8]*8, [0]*8]

for i, c in enumerate("NES.J"):
    tiles[97 + i] = [[0]*8, [rev(b) for b in IBM[ord(c)]]]

pcf = PcfFontFile.PcfFontFile(open(fontdir / "koi5x8.pcf", "rb"))
def g5(c):
    im = pcf.glyph[ord(c)][3]
    return [sum((1 << (4 - x)) for x in range(5) if im.getpixel((x, y))) for y in range(8)]

for d in range(10):
    g = g5(str(d))
    tiles[102 + d] = [[((v << 3) >> 4) & 0xFF for v in g], [0]*8]
    tiles[112 + d] = [[((v << 3) >> 1) & 0xFF for v in g], [0]*8]

font = b"".join(bytes(a) + bytes(b) for a, b in tiles)
(outdir / "font.chr").write_bytes(font)
glyph = {chr(c): g5(chr(c)) for c in range(33, 127)}
glyph['.'] = [0, 0, 0, 0, 0, 0b01100, 0b01100, 0]
glyph[','] = [0, 0, 0, 0, 0, 0b01100, 0b00100, 0b01000]
out = ["; generated by mkfont.py", "_glyph5:"]

for c in range(33, 127):
    out.append("  .byte " + ",".join(str(v) for v in glyph[chr(c)]) + f"   ; {chr(c)!r}")
shr = [((v << 3) >> b) & 0xFF for b in range(8) for v in range(32)]
shl = [((v << 3) << (8 - b)) & 0xFF if b else 0 for b in range(8) for v in range(32)]
out.append("_shr_tab:")

for i in range(0, 256, 32): out.append("  .byte " + ",".join(map(str, shr[i:i+32])))
out.append("_shl_tab:")

for i in range(0, 256, 32): out.append("  .byte " + ",".join(map(str, shl[i:i+32])))
(outdir / "font5.inc").write_text("\n".join(out) + "\n")

print("font.chr", len(font), "font5.inc ok")
